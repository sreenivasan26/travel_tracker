import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'
import { createHash } from 'node:crypto'

// Emits dist/sw.js with a precache list of every built file, so the app works offline after the first load.
const STATIC = ['./', './index.html', './manifest.webmanifest', './icon.svg', './icon-192.png', './icon-512.png', './apple-touch-icon.png']
function precacheSw() {
  return {
    name: 'precache-sw',
    apply: 'build',
    generateBundle(_, bundle) {
      const files = [...STATIC, ...Object.keys(bundle).filter((f) => !f.endsWith('.map') && f !== 'index.html' && !/(cyrillic|greek|vietnamese)/.test(f)).map((f) => './' + f)]
      const version = createHash('sha1').update(files.join('|') + Object.values(bundle).map((b) => b.fileName).join()).digest('hex').slice(0, 10)
      const src = `// generated by vite.config.js (precache-sw)
const CACHE = 'nt-travel-${version}'
const FILES = ${JSON.stringify(files)}
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('nt-travel-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()))
})
self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req).catch(() => (req.mode === 'navigate' ? caches.match('./index.html') : Response.error()))),
  )
})
`
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: src })
    },
  }
}

export default defineConfig({
  // Relative by default (works at a domain root and in any sub-folder). GitHub Pages: VITE_BASE=/travel_tracker/
  base: process.env.VITE_BASE || './',
  plugins: [react(), precacheSw()],
  server: { port: 5177 },
  build: { outDir: process.env.VITE_OUT || 'dist', emptyOutDir: true },
  test: { environment: 'node', include: ['src/**/*.test.js'] },
})
